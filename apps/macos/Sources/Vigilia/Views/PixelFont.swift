import CoreGraphics

/// A 5x7 bitmap font in the style of the banner's lettering. Uppercase only: lowercase letters
/// are drawn as capitals, and characters without a glyph as `?`. Punctuation is narrower.
enum PixelFont {
    static let height = 7
    /// Blank columns between two glyphs.
    static let spacing = 1

    /// The lit pixels of `text`, in font units, and its width.
    static func layout(_ text: String) -> (pixels: [CGPoint], width: Int) {
        var pixels: [CGPoint] = []
        var x = 0
        for (i, character) in text.uppercased().replacingOccurrences(of: "…", with: "...").enumerated() {
            let rows = glyphs[character] ?? glyphs["?"]!
            if i > 0 { x += spacing }
            for (y, row) in rows.enumerated() {
                for (dx, cell) in row.enumerated() where cell == "#" {
                    pixels.append(CGPoint(x: x + dx, y: y))
                }
            }
            x += rows[0].count
        }
        return (pixels, x)
    }

